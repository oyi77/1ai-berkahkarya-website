const WA = 'https://wa.me/6285732740006';

export const getStaticPaths: GetStaticPaths = async () => ({
  paths: [{ params: { locale: 'id' } }, { params: { locale: 'en' } }],
  fallback: false,
});

export const getStaticProps: GetStaticProps<PropertyProps> = async ({ params }) => {
  const locale = (params?.locale as Locale) || 'id';
  const empty = { locale, assets: [], fetchedAt: '', sourceCount: 0, sourceError: true };

  try {
    // Build-time read of a read-only SQLite snapshot of lelang-screener.
    // Static export has no API routes; CORS is irrelevant. Generated by
    // scripts/generate-malang-assets.py; missing values stay null.
    const file = path.join(process.cwd(), 'public', 'data', 'malang-assets.json');
    const raw = fs.readFileSync(file, 'utf-8');
    const data = JSON.parse(raw);
    const assets: AuctionAsset[] = Array.isArray(data?.assets) ? data.assets : [];
    const clean = assets.filter((a) => {
      const city = String(a.city || '').toUpperCase();
      return city.includes('MALANG') && !city.includes('PEMALANG');
    });
    return {
      props: {
        locale,
        assets: clean,
        fetchedAt: String(data?.generatedAt || ''),
        sourceCount: Number(data?.count) || clean.length,
        sourceError: false,
      },
    };
  } catch {
    return { props: empty };
  }
};

